import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { describe, expect, it } from "vitest";

const root = join(__dirname, "..", "..");

const SCAN_DIRS = ["src", "src-tauri/src", "mobile/src", "mobile/tests", "mobile/modules", "host", "tests"];
const SCAN_FILES = ["src-tauri/Info.plist", ...readdirSync(join(root, "src-tauri")).filter((n) => /^tauri.*\.conf\.json$/.test(n)).map((n) => `src-tauri/${n}`)];
const SKIP_DIRS = new Set(["node_modules", "target", "dist", "build", ".expo", "Pods", ".gradle", "generated"]);
const TEXT_EXT = /\.(tsx?|jsx?|css|html|rs|mjs|json|md|toml|swift|h|m|kt|gradle|podspec)$/;
const LOCKFILES = /(package-lock\.json|Cargo\.lock|yarn\.lock|pnpm-lock\.yaml)$/;
// Generated by mobile/scripts from providerSvgs.ts; embeds base64 icon data.
const GENERATED = /transcript-artwork\.json$/;

// Typography tokens that legitimately contain "mono"; stripped before matching.
// Font families are matched generally ("Roboto Mono", "IBM Plex Mono") rather
// than by a list. Those need case-sensitive capitals, so the CSS/OS keywords
// live in a separate case-insensitive pattern.
const FONT_FAMILY = new RegExp(
  [
    String.raw`\b[A-Z][A-Za-z]*(?: [A-Z][A-Za-z]*)* ?Mono\b`, // Roboto Mono, IBM Plex Mono, SF Mono
    String.raw`\b[A-Z][a-z]+Mono(?:-[A-Za-z]+)?\b`, // JetBrainsMono
    String.raw`SFMono-[A-Za-z]+`,
  ].join("|"),
  "g",
);
const TYPOGRAPHY_KEYWORDS =
  /ui-monospace|monospace|font-mono|monokai|monochrome|mono(?:repo|tonic|lith|graph|poly|type)/gi;

function stripTypography(text: string): string {
  return text.replace(FONT_FAMILY, "").replace(TYPOGRAPHY_KEYWORDS, "");
}

// Narrow, per-file line allowlist. Each entry is one specific deliberate use.
const ALLOWED: { file: string; line: RegExp; why: string }[] = [
  { file: "src/test/noMonoReferences.test.ts", line: /./, why: "this guard names the pattern it forbids" },
  { file: "src/test/sharedContracts.test.ts", line: /./, why: "asserts the GPUI app no longer reads the legacy MonoCode values" },
  { file: "src/test/upstreamLinks.test.ts", line: /usemono/, why: "this guard names the upstream URL it forbids" },
  { file: "mobile/src/ui/theme.ts", line: /./, why: "the unrelated monochrome-style \"mono\" theme (brief)" },
  { file: "src-tauri/src/pilot_transcript.rs", line: /no_mono_tables|"mono_"|stale mono table/, why: "asserts legacy tables are gone" },
  { file: "src/test/invokeCommands.test.ts", line: /legacy mono_\*|\/mono\//, why: "asserts no legacy mono commands" },
  { file: "src/features/sessions/model/operatorCommand.test.ts", line: /\/mono\b/, why: "retired /mono is plain text" },
  { file: "mobile/modules/rebase-link/ios/TranscriptPresentation.swift", line: /\bmono\b/, why: "`mono` selects the Menlo monospace font for code runs" },
  { file: "src/features/automations/model/automations.ts", line: /monopolize/, why: "the English word, not the old feature name" },
  { file: "src/features/pilots/model/pilotFiles.test.ts", line: /Monos\?/, why: "asserts no Mono wording" },
];

const THEME_LINE = /theme.*["']mono["']/;
const REVERSE_DAMAGE =
  /(SF|JetBrains|Liberation|Nerd Font|Symbols Nerd Font)\s?Pilot|Pilotspace|font-pilot|pilot(repo|tonic|lith|graph|poly|type)/i;

// "pilot" embedded in another word is a find-and-replace accident ("pilotpolize"
// for "monopolize"). camelCase (createPilot) and plurals (pilots) are fine.
const EMBEDDED_PILOT = /[A-Za-z]pilot|pilot(?!s?(?![a-z]))[a-z]/;
// Real identifiers that contain "pilot" inside a word.
const EMBEDDED_PILOT_OK: { token: RegExp; why: string }[] = [
  { token: /copilot/gi, why: "GitHub Copilot provider" },
  { token: /pilotartifact/g, why: "registered URI scheme (artifacts.rs / artifacts.ts)" },
  { token: /railpilotspinnedchange/g, why: "DOM event name for the rail Pilots pin setting" },
];
const hasEmbeddedPilot = (line: string) =>
  EMBEDDED_PILOT.test(EMBEDDED_PILOT_OK.reduce((t, a) => t.replace(a.token, ""), line));

function walk(dir: string, out: string[] = []): string[] {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of entries) {
    if (SKIP_DIRS.has(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (TEXT_EXT.test(name) && !LOCKFILES.test(name) && !GENERATED.test(name)) out.push(full);
  }
  return out;
}

function scannedFiles(): string[] {
  const files = SCAN_DIRS.flatMap((d) => walk(join(root, d)));
  for (const rel of SCAN_FILES) files.push(join(root, rel));
  for (const name of readdirSync(root)) {
    if (name.endsWith(".html") || name === "vite.config.ts") files.push(join(root, name));
  }
  return files;
}

function read(rel: string): string {
  return readFileSync(join(root, rel), "utf8");
}

function scan(pattern: (line: string) => boolean, honorAllowlist: boolean): string[] {
  const hits: string[] = [];
  for (const file of scannedFiles()) {
    const rel = relative(root, file);
    if (!honorAllowlist && rel === "src/test/noMonoReferences.test.ts") continue; // holds the forbidden pattern
    const rules = honorAllowlist ? ALLOWED.filter((a) => a.file === rel) : [];
    readFileSync(file, "utf8")
      .split("\n")
      .forEach((line, i) => {
        if (rules.some((r) => r.line.test(line))) return;
        if (honorAllowlist && THEME_LINE.test(line)) return;
        if (pattern(line)) hits.push(`${rel}:${i + 1}`);
      });
  }
  return hits;
}

describe("Monos -> Pilots rename", () => {
  it("leaves no stray mono references", () => {
    const offenders = scan((l) => /mono/i.test(stripTypography(l)), true);
    expect(offenders).toEqual([]);
  });

  it("did not damage font names or typography tokens", () => {
    expect(scan((l) => REVERSE_DAMAGE.test(l), false)).toEqual([]);
  });

  it("has no 'pilot' embedded inside another word", () => {
    expect(scan(hasEmbeddedPilot, true)).toEqual([]);
  });

  it("treats font family names as typography but not Mono-prefixed identifiers", () => {
    const strip = stripTypography;
    for (const font of ["Roboto Mono", "IBM Plex Mono", "SF Mono", "JetBrainsMono", "SFMono-Regular", "ui-monospace", "var(--font-mono)"]) {
      expect(/mono/i.test(strip(`font-family: "${font}"`)), font).toBe(false);
    }
    for (const stray of ["MonoScreen", "const monoList = []", "open the Mono tab"]) {
      expect(/mono/i.test(strip(stray)), stray).toBe(true);
    }
  });

  it("catches an embedded pilot but not camelCase or plurals", () => {
    for (const bad of ["pilotpolize", "copilot", "autopilots"]) expect(EMBEDDED_PILOT.test(bad), bad).toBe(true);
    for (const ok of ["createPilot", "isPilotSession", "pilots", "pilot-id", "the pilot."]) expect(EMBEDDED_PILOT.test(ok), ok).toBe(false);
  });

  it("kept monospace typography", () => {
    expect(read("src/styles/index.css")).toMatch(/font-mono|monospace/);
  });

  it("scans the mobile tree", () => {
    const rels = scannedFiles().map((f) => relative(root, f));
    expect(rels.some((f) => f.startsWith("mobile/src/"))).toBe(true);
    expect(rels.some((f) => f.includes("node_modules"))).toBe(false);
  });
});
